// Reads the header ("frontmatter") of every public/notes/*.md file and writes the list of notes
// used by the Notes app. Writing an article = adding ONE Markdown file, nothing else.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const NOTES_DIR = 'public/notes';
const OUTPUT_FILE = 'src/app/data/notes.generated.ts';
const CATEGORIES = ['dev', 'art', 'learning', 'women in tech', 'life'];
const REQUIRED_FIELDS = ['title', 'date', 'category', 'summary'];
const OPTIONAL_FIELDS = ['externalUrl', 'language'];

function readFrontmatter(markdown, fileName) {
  const frontmatter = markdown.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!frontmatter) {
    throw new Error(`${fileName}: the "---" header block is missing at the top of the file.`);
  }

  const fields = {};
  for (const line of frontmatter[1].split(/\r?\n/)) {
    const colonIndex = line.indexOf(':');
    if (colonIndex === -1) {
      continue;
    }
    const key = line.slice(0, colonIndex).trim();
    const value = line
      .slice(colonIndex + 1)
      .trim()
      .replace(/^["']|["']$/g, '');
    fields[key] = value;
  }
  return fields;
}

function toNote(fileName) {
  const fields = readFrontmatter(readFileSync(`${NOTES_DIR}/${fileName}`, 'utf8'), fileName);

  for (const field of REQUIRED_FIELDS) {
    if (!fields[field]) {
      throw new Error(`${fileName}: "${field}" is missing in the header.`);
    }
  }
  if (!CATEGORIES.includes(fields.category)) {
    throw new Error(`${fileName}: category must be one of: ${CATEGORIES.join(', ')}.`);
  }
  if (!/^\d{4}-\d{2}-\d{2}$/.test(fields.date)) {
    throw new Error(`${fileName}: date must look like 2026-10-05.`);
  }

  const note = { slug: fileName.replace(/\.md$/, '') };
  for (const field of [...REQUIRED_FIELDS, ...OPTIONAL_FIELDS]) {
    if (fields[field]) {
      note[field] = fields[field];
    }
  }
  return note;
}

const notes = readdirSync(NOTES_DIR)
  .filter((fileName) => fileName.endsWith('.md'))
  .map(toNote)
  .sort((first, second) => second.date.localeCompare(first.date));

writeFileSync(
  OUTPUT_FILE,
  `// Generated by scripts/build-notes-index.mjs from public/notes/*.md. Do not edit by hand.
import type { Note } from './notes';

export const GENERATED_NOTES: readonly Note[] = ${JSON.stringify(notes, null, 2)};
`,
);
console.log(`Notes index: ${notes.length} note(s) written to ${OUTPUT_FILE}`);
